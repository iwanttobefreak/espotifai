import java.util.Properties

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
    id("org.jetbrains.kotlin.plugin.compose")
}

val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("keystore.properties")
if (keystorePropertiesFile.exists()) {
    keystoreProperties.load(keystorePropertiesFile.inputStream())
}

android {
    namespace = "com.espotifai.app"
    compileSdk = 34

    defaultConfig {
        applicationId = "com.espotifai.app"
        minSdk = 26
        targetSdk = 34
        versionCode = 14
        versionName = "1.12"

        // Direcciones por defecto, configurables al compilar:
        //   ./gradlew assembleRelease -Pespotifai.urlCasa=http://... -Pespotifai.urlFuera=https://...
        val urlCasa = project.findProperty("espotifai.urlCasa")?.toString()
            ?: "http://192.0.2.10:8088"
        val urlFuera = project.findProperty("espotifai.urlFuera")?.toString()
            ?: "https://music.example.com"
        buildConfigField("String", "URL_CASA", "\"$urlCasa\"")
        buildConfigField("String", "URL_FUERA", "\"$urlFuera\"")
    }

    signingConfigs {
        create("release") {
            if (keystorePropertiesFile.exists()) {
                storeFile = file(keystoreProperties["storeFile"] as String)
                storePassword = keystoreProperties["storePassword"] as String
                keyAlias = keystoreProperties["keyAlias"] as String
                keyPassword = keystoreProperties["keyPassword"] as String
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            // Firma solo si existe keystore.properties (no se versiona).
            // Sin ella, el APK de release sale sin firmar: vale para probar.
            if (keystorePropertiesFile.exists()) {
                signingConfig = signingConfigs.getByName("release")
            }
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
    lint {
        checkReleaseBuilds = false
        abortOnError = false
    }
}

